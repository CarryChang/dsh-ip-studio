#!/usr/bin/env node
/**
 * Derive the portable Agent-Skill runtime from the compiled, DSH-free tool modules.
 *
 * `skills/dsh-ip-studio/` must install standalone into Claude Code / Cursor / Copilot (the open
 * Agent Skills format Agensi.io lists), with no DeepSeek Harness present. The deterministic logic
 * lives once in `src/*.ts`; after `tsc` it emits `lib/{review,formatters,outline}.js` — modules with
 * zero imports, verified by the check below. This script copies exactly those compiled modules into
 * the skill's `scripts/lib/`, so `src` stays the single source of truth and the skill never drifts.
 *
 * Run after `build`. Invoked from `check` and `prepack`; the result is committed so a GitHub clone
 * or `dsh plugin add github:` needs no build on the user's side.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const libDir = join(root, 'lib')
const targetDir = join(root, 'skills', 'dsh-ip-studio', 'scripts', 'lib')

/** Compiled modules the standalone CLI imports; each must carry no runtime import. */
const MODULES = ['review.js', 'formatters.js', 'outline.js']

const header = [
  '/* Generated by scripts/build-portable.mjs from lib/ (compiled from src/).',
  '   Edit src/*.ts, run `pnpm run build && pnpm run build:portable`. Do not hand-edit. */',
  '',
].join('\n')

for (const file of MODULES) {
  const source = join(libDir, file)
  let text
  try {
    text = readFileSync(source, 'utf8')
  } catch {
    throw new Error(`Missing ${source}; run \`pnpm run build\` before build:portable.`)
  }
  // A stray runtime import here would break the skill outside the DSH workspace.
  if (/^\s*import\s/m.test(text) || /from\s+['"]@deepseek-ai/.test(text)) {
    throw new Error(`lib/${file} has a runtime import; the portable skill must stay dependency-free.`)
  }
  mkdirSync(targetDir, { recursive: true })
  writeFileSync(join(targetDir, file), header + text)
}

console.log(`build:portable → skills/dsh-ip-studio/scripts/lib/ {${MODULES.join(', ')}}`)
